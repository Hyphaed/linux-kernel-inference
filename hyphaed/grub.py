GRUB_MENU_DISTRIBUTOR = "Ubuntu"


def pin_default_kernel(kver: str, *, dry_run: bool = False) -> None:
    """Persistently pin `kver` (e.g. '7.1.5-hyphaed') as the GRUB default
    boot entry via `grub-set-default`, so a future `update-grub` menu
    regeneration can't silently change which kernel boots by default.

    Unlike `grub-reboot` (one-shot), `grub-set-default` writes grubenv's
    saved_entry persistently — the correct semantics here, since the whole
    point is "this stays the intended default until the next hyphaed
    install changes it again".
    """
    entry = f"Advanced options for {GRUB_MENU_DISTRIBUTOR}>{GRUB_MENU_DISTRIBUTOR}, with Linux {kver}"
    if dry_run:
        log.info(f"would run: sudo grub-set-default {entry!r}")
        return
    run_sudo(["grub-set-default", entry])
    log.ok(f"pinned GRUB default boot entry → {kver}")


def write_label_dropin(*, dry_run: bool = False) -> bool:
    """Set GRUB_DISTRIBUTOR + bump GRUB_TIMEOUT to 5s. Returns True if changed."""
    if GRUB_LABEL_DROPIN.exists():
        try:
            if GRUB_LABEL_DROPIN.read_text() == GRUB_LABEL_DROPIN_BODY:
                return False
        except OSError:
            pass
    if dry_run:
        log.info(f"would write {GRUB_LABEL_DROPIN}")
        return True
    run_sudo(["mkdir", "-p", str(GRUB_LABEL_DROPIN.parent)])
    run_sudo(["tee", str(GRUB_LABEL_DROPIN)], input_str=GRUB_LABEL_DROPIN_BODY, capture=True)
    log.ok(f"wrote GRUB label drop-in {GRUB_LABEL_DROPIN}")
    return True
