def _parse_cpu_range(spec: str) -> set[int]:
    """"0-3,8-15" -> {0,1,2,3,8,9,...,15}. Inverse of topology._mask()."""
    cpus: set[int] = set()
    for part in spec.split(","):
        part = part.strip()
        if not part:
            continue
        if "-" in part:
            lo, hi = part.split("-", 1)
            cpus.update(range(int(lo), int(hi) + 1))
        else:
            cpus.add(int(part))
    return cpus

