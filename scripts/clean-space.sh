#!/usr/bin/env bash
# Free space on /boot and in build/. Dry run by default: prints what it would do.
#   bash scripts/clean-space.sh                 # report only
#   sudo bash scripts/clean-space.sh --go       # do it (needs root for /boot + apt purge)
#   KEEP=2 sudo bash scripts/clean-space.sh --go
#
# /boot: removes dangling symlinks (vmlinuz.old -> a deleted kernel), boot files that no
#   installed package owns, and installed *-hyphaed kernels other than the running one and
#   the newest KEEP. Never touches the running kernel, the stock -generic kernels, or efi/grub.
# build/: removes old build/linux-7.x trees (~30 GB each), keeping the newest KEEP, the running
#   kernel's tree, and the tree of the version under PREV/VER. Also old debs in out/debs.
set -euo pipefail
GO=0; [ "${1:-}" = "--go" ] && GO=1
KEEP="${KEEP:-2}"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
RUNNING="$(uname -r)"                     # e.g. 7.2.12-hyphaed
RUNVER="${RUNNING%%-*}"
do_() { if [ "$GO" = 1 ]; then echo "+ $*"; "$@"; else echo "would: $*"; fi; }
[ "$GO" = 1 ] && [ "$(id -u)" != 0 ] && { echo "--go needs sudo (touches /boot and dpkg)" >&2; exit 1; }

echo "== /boot ($(df -h /boot | awk 'NR==2{print $4" free of "$2}')), running kernel $RUNNING"

echo "-- dangling symlinks"
for l in /boot/vmlinuz /boot/vmlinuz.old /boot/initrd.img /boot/initrd.img.old; do
  [ -L "$l" ] && [ ! -e "$l" ] && do_ rm -f "$l"
done

echo "-- installed hyphaed kernels beyond the keep set"
mapfile -t hy < <(dpkg-query -W -f='${Package}\n' 'linux-image-*-hyphaed' 2>/dev/null | sed 's/linux-image-//; s/-hyphaed//' | sort -V)
keep_set=("$RUNVER"); n=${#hy[@]}
for ((i = n > KEEP ? n - KEEP : 0; i < n; i++)); do keep_set+=("${hy[$i]}"); done
for v in "${hy[@]}"; do
  if printf '%s\n' "${keep_set[@]}" | grep -qx "$v"; then echo "keep $v"; continue; fi
  pk=$(dpkg-query -W -f='${Package}\n' "linux-*-$v-hyphaed" 2>/dev/null | tr '\n' ' ')
  do_ apt-get purge -y $pk
done

echo "-- boot files no installed package owns (kernel/initrd/System.map/config of removed kernels)"
for f in /boot/vmlinuz-* /boot/initrd.img-* /boot/System.map-* /boot/config-*; do
  [ -e "$f" ] || continue
  dpkg -S "$f" >/dev/null 2>&1 && continue
  # initrd images are generated by dracut/initramfs-tools, so dpkg does not own them:
  # keep one if a matching /lib/modules/<ver> still exists.
  base="${f#/boot/}"; kv="${base#*-}"
  [ -d "/lib/modules/$kv" ] && continue
  echo "orphan: $f (no /lib/modules/$kv)"; do_ rm -f "$f"
done
[ "$GO" = 1 ] && update-grub 2>&1 | tail -2 || echo "would: update-grub"

echo; echo "== build/ ($(df -h "$ROOT" | awk 'NR==2{print $4" free of "$2}'))"
cd "$ROOT"
mapfile -t trees < <(ls -d build/linux-7.* 2>/dev/null | sort -V)
tn=${#trees[@]}
for ((i = 0; i < tn; i++)); do
  t="${trees[$i]}"; v="${t#build/linux-}"
  if ((i >= tn - KEEP)) || [ "$v" = "$RUNVER" ] || [ "$v" = "${VER:-}" ] || [ "$v" = "${PREV:-}" ]; then
    echo "keep $t ($(du -sh "$t" | cut -f1))"; continue; fi
  echo "remove $t ($(du -sh "$t" | cut -f1))"
  # the repo owner owns build/, so drop privileges for the delete
  if [ "$GO" = 1 ] && [ -n "${SUDO_USER:-}" ]; then do_ sudo -u "$SUDO_USER" rm -rf "$t"; else do_ rm -rf "$t"; fi
done
# stale packaging leftovers of removed trees (.buildinfo/.changes/.deb in build/)
find build -maxdepth 1 -type f \( -name '*.buildinfo' -o -name '*.changes' \) -mtime +14 \
  -printf 'stale %p\n' -exec bash -c '[ "$1" = 1 ] && rm -f "$2"' _ "$GO" {} \;

echo; echo "== out/debs (keep newest $KEEP versions + running)"
mapfile -t dv < <(ls out/debs 2>/dev/null | sed -n 's/^linux-image-\(7\.[0-9.]*\)-hyphaed.*/\1/p' | sort -V)
dn=${#dv[@]}
for ((i = 0; i < dn - KEEP; i++)); do
  v="${dv[$i]}"; [ "$v" = "$RUNVER" ] && continue
  for f in out/debs/*"$v"*; do if [ "$GO" = 1 ] && [ -n "${SUDO_USER:-}" ]; then sudo -u "$SUDO_USER" rm -f "$f"; else do_ rm -f "$f"; fi; done
done
echo; df -h /boot / | awk 'NR>1{print $6": "$4" free"}'
[ "$GO" = 1 ] || echo "(dry run: nothing changed. Re-run with: sudo bash scripts/clean-space.sh --go)"
